# Proyecto Retail - Esquema Base y Carga de Datos

## Descripción
Este repositorio contiene el script SQL para la creación del esquema base de un proyecto de retail, incluyendo las tablas principales (`clientes`, `productos` y `ventas`) con sus respectivas restricciones de integridad y una carga inicial de datos.

## Cómo ejecutar el script
1. Abre tu gestor de base de datos preferido (ej. pgAdmin, DBeaver, MySQL Workbench, DBeaver).
2. Ejecuta el comando para crear la base de datos: `CREATE DATABASE retail_project;`
3. Conéctate a la base de datos `retail_project`.
4. Abre el archivo `retail_project.sql` que se encuentra en este repositorio.
5. Ejecuta el script completo para crear las tablas, aplicar las restricciones e insertar los datos de prueba.
